import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import {zipEntry as readZipEntry} from './read-zip-entry.mjs';
const compiled=ts.transpileModule(fs.readFileSync('lib/browser-support.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const exports={};new Function('exports',compiled)(exports);
const context=vm.createContext({setTimeout,AbortController});
vm.runInContext(`window=globalThis;AbortSignal=function(){};Object.hasOwn=undefined;Array.prototype.at=undefined;Promise.allSettled=undefined;`,context);
vm.runInContext(exports.browserSupportScript,context);
assert.equal(vm.runInContext(`Object.hasOwn({x:1},'x')&&!Object.hasOwn(Object.create({x:1}),'x')`,context),true);
assert.equal(vm.runInContext(`[1,2,3].at(-1)`,context),3);
assert.equal(await vm.runInContext(`Promise.allSettled([Promise.resolve(7),Promise.reject('bad')]).then(r=>r[0].value===7&&r[1].reason==='bad')`,context),true);
assert.equal(await vm.runInContext(`new Promise(resolve=>{var s=AbortSignal.timeout(5);s.addEventListener('abort',()=>resolve(s.aborted));})`,context),true);
assert.equal(vm.runInContext(`var a=new AbortController(),b=new AbortController(),s=AbortSignal.any([a.signal,b.signal]);b.abort();s.aborted`,context),true);
const release=JSON.parse(fs.readFileSync('public/downloads/android-build.json','utf8'));
const apk=fs.readFileSync('public'+release.download);
const html=readZipEntry(apk,'assets/shell/index.html').toString();
assert(html.includes('RACE WEEKEND')&&html.includes('赛事时间安排')&&html.includes('美国大奖赛'),'Bundled HTML must include race data before scripts run');
const scripts=[...html.matchAll(/(?:src|href)="(\/_next\/static\/[^"?]+\.js)"/g)].map(m=>m[1]);
assert(scripts.length>0);
for(const script of scripts)assert(readZipEntry(apk,'assets/shell'+script).length>0,'Every bootstrap script must be bundled');
for(const name of fs.readdirSync('public/cars'))if(name.endsWith('.png'))assert(readZipEntry(apk,'assets/shell/cars/'+name).equals(fs.readFileSync('public/cars/'+name)),'Every team car must be bundled unchanged');
assert(!/fixture-refresh-token|sb_publishable_|sb_secret_|service_role/.test(html),'Bootstrap HTML must contain no credentials');
console.log('Startup recovery: old-browser API shims, timed/cancelled requests, pre-rendered race data and all bundled bootstrap scripts passed.');
