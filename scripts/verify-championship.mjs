import assert from 'node:assert/strict';
import {clinchConditions} from '../lib/championship.ts';
import fs from 'node:fs';
const drivers=JSON.parse(fs.readFileSync(new URL('../lib/snapshots/drivers_standings_2026_zh.json',import.meta.url))).data.items[0].standings;
const target=drivers.find(d=>d.tla==='ANT');
const result=clinchConditions(target,drivers,1,null,125,5);
const russell=result.find(c=>c.rival.driverId===drivers.find(d=>d.tla==='RUS').driverId);
const hamilton=result.find(c=>c.rival.driverId===drivers.find(d=>d.tla==='HAM').driverId);
assert.ok(russell.allowed.some(a=>a.race===9&&a.tie&&a.tieSafe));
assert.ok(!russell.allowed.some(a=>a.race===8));
assert.ok(hamilton.allowed.some(a=>a.race===5&&!a.tie));
assert.ok(!hamilton.allowed.some(a=>a.race===4));
assert.ok(result.every(c=>c.allowed.some(a=>!a.tie||a.tieSafe)));
assert.ok(result.every(c=>c.allowed.every(a=>a.race!==1)),'Two drivers cannot both finish P1');
assert.ok(clinchConditions(target,drivers,2,null,125,5).some(c=>!c.allowed.some(a=>!a.tie||a.tieSafe)),'P2 cannot clinch at Austin');
const noCountback=clinchConditions({...target,wins:undefined},drivers,1,null,125,5);
assert.equal(noCountback.find(c=>c.rival.driverId===russell.rival.driverId).allowed.find(a=>a.race===9).tieSafe,false);
const sprint=clinchConditions({driverId:'a',driverName:'A',points:100,wins:2},[{driverId:'b',driverName:'B',points:100,wins:2}],1,1,0,0)[0];
assert.ok(sprint.allowed.every(a=>a.race!==1&&a.sprint!==1));
assert.ok(sprint.allowed.some(a=>a.race===2&&a.sprint===2&&a.points===25));
assert.equal(clinchConditions({driverId:'a',driverName:'A',points:0,wins:1},[{driverId:'b',driverName:'B',points:0,wins:3}],1,null,25,1)[0].allowed.find(a=>a.race===11)?.tieSafe,false);
console.log('Championship checks passed: Austin constraints, wins countback, unresolved ties, sprint scoring and unique positions.');
