import assert from 'node:assert/strict';
import { accountRequest } from '../lib/account-client';
import { publicAuthAvailability, unifiedAuthConfig } from '../lib/auth/config';
import { AccountService } from '../lib/auth/accountService';
import { AccountController } from '../lib/auth/AccountController';
import { AccountCookies, RecoveryGrant } from '../lib/auth/cookies';
import type { AccountRepository } from '../lib/auth/contracts';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { AuthScreen } from '../app/auth-screen';
const env={AUTH_MODE:'required',AUTH_BASE_URL:'https://f1.xiaodinglab.com',SUPABASE_URL:'https://fixture.supabase.co',SUPABASE_PUBLISHABLE_KEY:'sb_publishable_fixture_for_tests_only',AUTH_SESSION_SECRET:'fixture-secret-at-least-32-characters-long'};
const config=unifiedAuthConfig(env),cookies=new AccountCookies(new Request(config.baseUrl),config);
let calls=0;
const unsupported=async()=>{throw new Error('Unexpected provider operation');};
const provider:AccountRepository={current:async()=>{calls++;throw new Error('Simulated expired-session provider outage');},login:unsupported,register:unsupported,resend:unsupported,recover:unsupported,verify:unsupported,updatePassword:unsupported,uploadAvatar:unsupported,removeAvatar:unsupported,downloadAvatar:unsupported,logout:unsupported,clearSession:()=>{throw new Error('Unexpected session mutation');}};
const service=new AccountService(config,provider,cookies,new RecoveryGrant(cookies,config.sessionSecret));
const controller=new AccountController(config,service,cookies,env);
assert.deepEqual(publicAuthAvailability(env),{enabled:true,configured:true});
assert.deepEqual(await controller.availability().json(),{enabled:true,configured:true});
assert.equal(calls,0,'Rendering an available login form never waits for an expired session');
assert.equal((await controller.session()).status,503,'Session identity still fails closed during provider outages');
assert.equal(calls,1);
assert.deepEqual(publicAuthAvailability({AUTH_MODE:'required'}),{enabled:true,configured:false});
assert.match(controller.availability().headers.get('cache-control')!,/no-store/);
const formHtml=renderToStaticMarkup(createElement(AuthScreen,{mode:'login',availability:publicAuthAvailability(env)}));
assert.match(formHtml,/<form[^>]+method="post"/,'An unhydrated form never sends credentials in a GET URL');
assert.match(formHtml,/<button[^>]+disabled=""[^>]+type="submit"/,'Submitting remains disabled until React owns the form');
const ok: typeof fetch = async (_url,options) => { assert.equal(options?.credentials,'same-origin'); assert.equal(options?.method,'POST'); return Response.json({next:'/#schedule'}); };
assert.equal((await accountRequest('login',{},ok)).next,'/#schedule');
const invalid:typeof fetch=async()=>Response.json({code:'INVALID_CREDENTIALS',error:'邮箱或密码不正确。'},{status:401});
await assert.rejects(accountRequest('login',{},invalid),(error:unknown)=>error instanceof Error&&error.message==='邮箱或密码不正确。');
for(const status of [403,502,503]){
 const html:typeof fetch=async()=>new Response('<html>gateway error</html>',{status,headers:{'Content-Type':'text/html'}});
 await assert.rejects(accountRequest('login',{},html),(error:unknown)=>error instanceof Error&&!error.message.includes('<html>')&&!error.message.includes('JSON'));
}
const malformed:typeof fetch=async()=>Response.json('not an account response');
await assert.rejects(accountRequest('login',{},malformed));
const network:typeof fetch=async()=>{throw new TypeError('Failed to fetch');};
await assert.rejects(accountRequest('login',{},network),/网络连接中断/);
const timeout:typeof fetch=async()=>{throw new DOMException('expired','TimeoutError');};
await assert.rejects(accountRequest('login',{},timeout),/连接超时/);
let attempts=0;
const limited:typeof fetch=async()=>{attempts++;return Response.json({error:'请求较频繁',code:'ACCOUNT_IP_LIMITED'},{status:429,headers:{'Retry-After':'60'}});};
await assert.rejects(accountRequest('login',{},limited),(error:unknown)=>typeof error==='object'&&error!==null&&'retryAfter' in error&&error.retryAfter===60);
assert.equal(attempts,1,'Never silently replay a credential-bearing POST');
console.log('Account client: login readiness does not query existing sessions; identity checks remain protected; JSON/HTML/network/timeout errors and single-submit rate-limit handling passed.');
