import assert from 'node:assert/strict';
import { podiumShareCard, readSharedSelection, shareWeather, weekendShareCard } from '../lib/share-card';
const season = '11111111-1111-4111-8111-111111111111', raceId = '22222222-2222-4222-8222-222222222222';
const at = Date.parse('2026-10-23T12:00:00Z');
const race = { id: raceId, name: '测试大奖赛', circuit: { name: '测试赛道' }, schedule: [{ id: 'race', type: 'MainRace', startDate: '2026-10-25T12:00:00Z', endDate: '2026-10-25T14:00:00Z' }] };
const card = weekendShareCard(race, season, 'Asia/Shanghai', '2026-10-23T12:00:00Z', 'snapshot');
assert.match(card.rows[0].value, /20:00/);
assert.match(card.subtitle, /2026 赛季/);
assert.match(card.dataNote, /赛事快照/);
const shared = readSharedSelection(new URL(card.url).search);
assert.equal(shared.race, raceId); assert.equal(shared.season, season);
assert.deepEqual(readSharedSelection('?season=https://evil.test&race=invalid&podium=' + season + ',bad'), { season: '', race: '', podium: [] });
assert.deepEqual(readSharedSelection('?podium=' + [season, season].join(',')).podium, [season]);
assert.deepEqual(readSharedSelection('?podium=' + [season, raceId, season, raceId].join(',')).podium, []);
const driver = { driverId: season, driverName: 'Driver', teamName: 'Team', teamColor: '84ecd7', email: 'never-share@example.test', memberId: 'private-member', avatarUrl: '/api/auth/avatar' };
const podium = podiumShareCard([driver], season);
assert.equal(podium.rows[0].color, '#84ecd7');
assert(!JSON.stringify(podium).includes('never-share')); assert(!JSON.stringify(podium).includes('private-member')); assert(!JSON.stringify(podium).includes('/api/auth/'));
assert.deepEqual(readSharedSelection(new URL(podium.url).search).podium, [season]);
const weather = { fetchedAt: at - 60000, data: { timezone: 'America/Chicago', hourly: { time: [Date.parse(race.schedule[0].startDate) / 1000], temperature_2m: [24.6], precipitation_probability: [20] } } };
assert.match(shareWeather(weather, race, at)!.summary, /25°C.*20%/);
assert.match(shareWeather({ ...weather, stale: true }, race, at)!.detail, /缓存/);
assert.equal(shareWeather({ ...weather, fetchedAt: at - 7 * 3600000 }, race, at), undefined);
assert.equal(shareWeather(weather, race, at + 7 * 86400000), undefined);
assert.equal(shareWeather({ fetchedAt: at, data: {} }, race, at), undefined);
assert.equal(shareWeather({ ...weather, fetchedAt: at + 60000 }, race, at), undefined);
assert.equal(shareWeather(weather, { ...race, schedule: [] }, at), undefined);
console.log('Share cards: timezone, safe deep links, read-only podium selections, private-data exclusion and forecast freshness passed.');
